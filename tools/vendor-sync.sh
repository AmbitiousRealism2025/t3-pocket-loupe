#!/usr/bin/env bash
# Copies T3 Loupe's shared view libraries into public/vendor/ as ES modules.
#
# The sources are QML `.pragma library` scripts: plain ES5 functions and vars at the top
# level. The transformation drops the pragma line, adds a provenance header, and appends
# one `export { … }` listing every top-level function and var. Nothing else changes.
# Reads from the installed plugin at its verified commit; refuses any other commit.
#   tools/vendor-sync.sh [plugin-dir]
set -euo pipefail
cd "$(dirname "$0")/.."
src="${1:-${T3_LOUPE_DIR:-$HOME/.config/omarchy/plugins/ambitiousrealism.t3-loupe}}"
want=6fb1ec8e2f7c573ca1178b038dfca15700926a7e
have=$(git -C "$src" rev-parse HEAD)
if [ "$have" != "$want" ]; then echo "vendor-sync: $src is at $have, want $want" >&2; exit 1; fi
if [ -n "$(git -C "$src" status --porcelain -- lib)" ]; then echo "vendor-sync: $src/lib has local changes" >&2; exit 1; fi

mkdir -p public/vendor
for name in Palette Format Icons Store; do
  in="$src/lib/$name.js"
  out="public/vendor/$(echo "$name" | tr '[:upper:]' '[:lower:]').js"
  exports=$(grep -oE '^(function|var) [A-Za-z_][A-Za-z0-9_]*' "$in" | awk '{print $2}' | sort -u | paste -sd, - | sed 's/,/, /g')
  {
    echo "// Vendored from T3 Loupe lib/$name.js at commit ${want:0:7} (MIT; see VENDOR.md)."
    echo "// Generated by tools/vendor-sync.sh: the QML pragma line is dropped and an export list added."
    grep -v '^\.pragma library' "$in"
    echo
    echo "export { $exports }"
  } >"$out"
  echo "vendor-sync: $out ($(wc -c <"$out") bytes)"
done
